-- Skema modul Sertifikasi Benih BP3MBTP (berdasarkan alur XML 7 aktor)
-- Fase 1: Verifikasi Lapangan | Fase 2: Pengujian Lab Mutu | Fase 3: Sertifikasi & Penerbitan Label

CREATE TABLE IF NOT EXISTS users (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    npp VARCHAR(50),
    unit_kerja VARCHAR(100),
    role VARCHAR(100) NOT NULL CHECK (role IN ('pelanggan','admin','pengawas','analis','penandatangan','legalisasi','percetakan')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id));

CREATE TABLE IF NOT EXISTS permohonan_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nomor_permohonan VARCHAR(100) NOT NULL UNIQUE,
    pelanggan_id BIGINT NOT NULL,
    jenis_benih VARCHAR(100) NOT NULL,
    varietas VARCHAR(100),
    luas_lahan DECIMAL(12,4),
    lokasi_kebun TEXT,
    status VARCHAR(100) NOT NULL DEFAULT 'diajukan' CHECK (status IN ('diajukan','dibayar','diverifikasi','diinspeksi','divalidasi','ditolak','dibatalkan')),
    pembayaran_awal_status VARCHAR(100) NOT NULL DEFAULT 'belum' CHECK (pembayaran_awal_status IN ('belum','lunas')),
    buku_induk_nomor VARCHAR(100),
    laporan_verifikasi TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (pelanggan_id) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS inspeksi_fase (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    permohonan_id BIGINT NOT NULL,
    fase SMALLINT NOT NULL,
    pengawas_id BIGINT NOT NULL,
    hasil VARCHAR(100) NOT NULL CHECK (hasil IN ('lulus','perlu_perbaikan','tidak_lulus')),
    catatan TEXT,
    tanggal_inspeksi DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id) ON DELETE CASCADE,
    FOREIGN KEY (pengawas_id) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS buku_induk (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    permohonan_id BIGINT NOT NULL UNIQUE,
    nomor_buku_induk VARCHAR(100) NOT NULL UNIQUE,
    catatan TEXT,
    dibuat_oleh BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id) ON DELETE CASCADE,
    FOREIGN KEY (dibuat_oleh) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS pembayaran (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    permohonan_id BIGINT NOT NULL,
    jenis VARCHAR(100) NOT NULL CHECK (jenis IN ('awal','akhir')),
    jumlah DECIMAL(18,2) NOT NULL,
    status VARCHAR(100) NOT NULL DEFAULT 'belum' CHECK (status IN ('belum','lunas','gagal')),
    bukti_transfer VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS sampel_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    permohonan_id BIGINT NOT NULL,
    kode_sampel VARCHAR(100) NOT NULL UNIQUE,
    pengawas_id BIGINT NOT NULL,
    analis_id BIGINT,
    jumlah_sampel INTEGER NOT NULL DEFAULT 1,
    tanggal_pengambilan DATE,
    status VARCHAR(100) NOT NULL DEFAULT 'dikumpulkan' CHECK (status IN ('dikumpulkan','dikodekan','diuji','selesai')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id) ON DELETE CASCADE,
    FOREIGN KEY (pengawas_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (analis_id) REFERENCES users(id) ON DELETE SET NULL);

CREATE TABLE IF NOT EXISTS uji_mutu (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    sampel_id BIGINT NOT NULL,
    parameter VARCHAR(100) NOT NULL,
    hasil TEXT NOT NULL,
    status_lulus BOOLEAN NOT NULL DEFAULT FALSE,
    catatan TEXT,
    diuji_oleh BIGINT NOT NULL,
    tanggal_uji DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (sampel_id) REFERENCES sampel_benih(id) ON DELETE CASCADE,
    FOREIGN KEY (diuji_oleh) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS laporan_mutu (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    sampel_id BIGINT NOT NULL UNIQUE,
    kesimpulan VARCHAR(100) NOT NULL CHECK (kesimpulan IN ('lulus','tidak_lulus')),
    isi_laporan TEXT NOT NULL,
    disusun_oleh BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (sampel_id) REFERENCES sampel_benih(id) ON DELETE CASCADE,
    FOREIGN KEY (disusun_oleh) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS sertifikat_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    permohonan_id BIGINT NOT NULL UNIQUE,
    nomor_sertifikat VARCHAR(100) NOT NULL UNIQUE,
    penandatangan_id BIGINT NOT NULL,
    tanggal_ttd TIMESTAMP,
    tte_status VARCHAR(100) NOT NULL DEFAULT 'belum' CHECK (tte_status IN ('belum','ditandatangani','gagal')),
    tte_dokumen_url VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id) ON DELETE CASCADE,
    FOREIGN KEY (penandatangan_id) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS draft_label (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    sertifikat_id BIGINT NOT NULL UNIQUE,
    kode_barcode VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(100) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','disetujui','dicetak','legalisasi')),
    integrasi_sim_status VARCHAR(100) NOT NULL DEFAULT 'belum' CHECK (integrasi_sim_status IN ('belum','terkirim','gagal')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (sertifikat_id) REFERENCES sertifikat_benih(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS label_legalisasi (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    draft_label_id BIGINT NOT NULL UNIQUE,
    legalisasi_id BIGINT NOT NULL,
    status VARCHAR(100) NOT NULL DEFAULT 'belum' CHECK (status IN ('belum','diverifikasi','ditolak','selesai')),
    catatan TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (draft_label_id) REFERENCES draft_label(id) ON DELETE CASCADE,
    FOREIGN KEY (legalisasi_id) REFERENCES users(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS penyerahan_dokumen (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    permohonan_id BIGINT NOT NULL UNIQUE,
    sertifikat_dikirim BOOLEAN NOT NULL DEFAULT FALSE,
    label_dikirim BOOLEAN NOT NULL DEFAULT FALSE,
    pembayaran_akhir_status VARCHAR(100) NOT NULL DEFAULT 'belum' CHECK (pembayaran_akhir_status IN ('belum','lunas','gagal')),
    tanggal_penyerahan TIMESTAMP,
    diterima_oleh VARCHAR(255),
    catatan TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    actor_id BIGINT,
    actor_role VARCHAR(50),
    action VARCHAR(100) NOT NULL,
    entity VARCHAR(100) NOT NULL,
    entity_id BIGINT,
    detail TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL);
