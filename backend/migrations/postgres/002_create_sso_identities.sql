CREATE TABLE IF NOT EXISTS sso_identities (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    issuer VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    realm VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_sso_identity_issuer_subject UNIQUE (issuer, subject),
    CONSTRAINT fk_sso_identity_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE);


CREATE INDEX IF NOT EXISTS idx_sso_identity_user ON sso_identities (user_id);
