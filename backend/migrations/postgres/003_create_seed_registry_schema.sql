-- Skema registrasi benih, persediaan per lot, dan penjualan benih.
-- Catatan: format nomor registrasi/dokumen resmi masih menunggu validasi BP3MBTP.

CREATE TABLE IF NOT EXISTS registrasi_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nomor_registrasi VARCHAR(120) NOT NULL UNIQUE,
    permohonan_id BIGINT NOT NULL,
    sertifikat_id BIGINT,
    draft_label_id BIGINT,
    nomor_sertifikat VARCHAR(100) NOT NULL,
    kode_label VARCHAR(100) NOT NULL,
    komoditas VARCHAR(100) NOT NULL,
    varietas VARCHAR(100) NOT NULL,
    produsen VARCHAR(200) NOT NULL,
    sumber_benih VARCHAR(200) NOT NULL,
    nomor_lot VARCHAR(100) NOT NULL UNIQUE,
    kelas_benih VARCHAR(100) NOT NULL CHECK (kelas_benih IN ('penjenis','dasar','pokok','sebar')),
    jumlah DECIMAL(18,3) NOT NULL,
    satuan VARCHAR(20) NOT NULL,
    tanggal_produksi DATE NOT NULL,
    tanggal_kedaluwarsa DATE NOT NULL,
    status_edar VARCHAR(100) NOT NULL DEFAULT 'aktif' CHECK (status_edar IN ('aktif','ditangguhkan','dicabut','kedaluwarsa')),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (permohonan_id) REFERENCES permohonan_benih(id),
    FOREIGN KEY (sertifikat_id) REFERENCES sertifikat_benih(id),
    FOREIGN KEY (draft_label_id) REFERENCES draft_label(id),
    FOREIGN KEY (created_by) REFERENCES users(id));

CREATE TABLE IF NOT EXISTS stok_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    registrasi_id BIGINT NOT NULL UNIQUE,
    jumlah_tersedia DECIMAL(18,3) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (registrasi_id) REFERENCES registrasi_benih(id));

CREATE TABLE IF NOT EXISTS mutasi_stok_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    registrasi_id BIGINT NOT NULL,
    jenis VARCHAR(100) NOT NULL CHECK (jenis IN ('masuk','keluar','koreksi')),
    jumlah DECIMAL(18,3) NOT NULL,
    saldo_setelah DECIMAL(18,3) NOT NULL,
    referensi_tipe VARCHAR(50) NOT NULL,
    referensi_id BIGINT,
    catatan TEXT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (registrasi_id) REFERENCES registrasi_benih(id),
    FOREIGN KEY (created_by) REFERENCES users(id));

CREATE TABLE IF NOT EXISTS penjualan_benih (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nomor_dokumen VARCHAR(120) NOT NULL UNIQUE,
    registrasi_id BIGINT NOT NULL,
    nomor_lot VARCHAR(100) NOT NULL,
    pembeli VARCHAR(200) NOT NULL,
    jumlah DECIMAL(18,3) NOT NULL,
    harga_satuan DECIMAL(18,2) NOT NULL,
    total_harga DECIMAL(20,2) NOT NULL,
    tanggal_transaksi DATE NOT NULL,
    status VARCHAR(100) NOT NULL DEFAULT 'selesai' CHECK (status IN ('selesai','dibatalkan')),
    alasan_pembatalan TEXT,
    dibatalkan_oleh BIGINT,
    dibatalkan_pada TIMESTAMP,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    FOREIGN KEY (registrasi_id) REFERENCES registrasi_benih(id),
    FOREIGN KEY (dibatalkan_oleh) REFERENCES users(id),
    FOREIGN KEY (created_by) REFERENCES users(id));


CREATE INDEX IF NOT EXISTS idx_registrasi_status_edar ON registrasi_benih (status_edar);
CREATE INDEX IF NOT EXISTS idx_registrasi_kedaluwarsa ON registrasi_benih (tanggal_kedaluwarsa);
CREATE INDEX IF NOT EXISTS idx_mutasi_registrasi ON mutasi_stok_benih (registrasi_id, id);
CREATE INDEX IF NOT EXISTS idx_penjualan_registrasi ON penjualan_benih (registrasi_id);
CREATE INDEX IF NOT EXISTS idx_penjualan_tanggal ON penjualan_benih (tanggal_transaksi);
CREATE INDEX IF NOT EXISTS idx_penjualan_status ON penjualan_benih (status);
