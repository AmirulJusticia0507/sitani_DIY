-- Batch impor repository data lokal. Kolom dataset tetap fleksibel sampai
-- template resmi, satuan, wilayah, dan aturan duplikasi ditetapkan.
CREATE TABLE IF NOT EXISTS dataset_imports (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nama_dataset VARCHAR(120) NOT NULL,
    nama_file VARCHAR(255) NOT NULL,
    headers_json JSONB NOT NULL,
    jumlah_baris INTEGER NOT NULL,
    baris_json JSONB NOT NULL,
    diunggah_oleh BIGINT NOT NULL,
    dibuat_pada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_dataset_imports_user FOREIGN KEY (diunggah_oleh) REFERENCES users(id) ON DELETE RESTRICT);


CREATE INDEX IF NOT EXISTS idx_dataset_imports_uploader ON dataset_imports (diunggah_oleh);
CREATE INDEX IF NOT EXISTS idx_dataset_imports_name ON dataset_imports (nama_dataset);
